#!/usr/bin/env bash
# setup-claude-code.sh
#
# Installs and configures the REAL Anthropic Claude Code CLI to run
# against your local Ollama daemon instead of Anthropic's API — free,
# no Anthropic account, no login, no API key. This works because:
#   - Ollama v0.14.0+ exposes an Anthropic Messages API-compatible
#     endpoint (https://ollama.com/blog/claude)
#   - Claude Code respects ANTHROPIC_BASE_URL to redirect requests
#     away from api.anthropic.com — an officially documented override,
#     not a workaround (https://code.claude.com/docs)
#
# This is SEPARATE from LCYcode.ai's own agent loop (main.py). That
# stays as-is — its own Describe/Plan/Execute/Review loop, its own
# tools, its own GUI. This script sets up a second, independent way
# to work in this project's workspace/: the actual Claude Code CLI,
# with its own (more mature) tool implementations, subagents, and
# permission flow, backed by whichever Ollama model you choose.
#
# Use LCYcode.ai's GUI/CLI when you want the browser view, resumable
# sessions, live diffs, and multi-provider routing built here. Use
# real Claude Code (via this script) when you want its more complete
# agentic feature set and don't need this project's extras.
set -e

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$ROOT"

BOLD='\033[1m'; CYAN='\033[36m'; GREEN='\033[32m'; YELLOW='\033[33m'; RED='\033[31m'; RESET='\033[0m'

echo -e "${CYAN}${BOLD}Claude Code + Ollama setup${RESET}"
echo "installing the real Claude Code CLI, pointed at your local Ollama — free, no Anthropic account"
echo

# 1. Read the Ollama host/model this project is already configured to use,
#    so Claude Code targets the same daemon rather than a second config.
OLLAMA_HOST=$(python3 - <<'PY'
import json
try:
    print(json.load(open("key.json")).get("ollama", {}).get("host", "http://127.0.0.1:11434"))
except Exception:
    print("http://127.0.0.1:11434")
PY
)
DEFAULT_MODEL=$(python3 - <<'PY'
import json
try:
    print(json.load(open("key.json")).get("ollama", {}).get("model", "deepseek-coder:1.3b"))
except Exception:
    print("deepseek-coder:1.3b")
PY
)
echo -e "${YELLOW}[1/4]${RESET} using ollama at ${OLLAMA_HOST} (from this project's key.json)"

# 2. Confirm the Ollama daemon is actually up.
if ! curl -fsS "${OLLAMA_HOST}/api/tags" >/dev/null 2>&1; then
  echo -e "        ${RED}ollama daemon not reachable at ${OLLAMA_HOST}${RESET}"
  echo "        run ./setup.sh first, or start it yourself with: ollama serve"
  exit 1
fi
echo "        daemon reachable"

# 3. Install the real Claude Code CLI if it isn't already.
echo -e "${YELLOW}[2/4]${RESET} checking for the claude CLI..."
if command -v claude >/dev/null 2>&1; then
  echo "        already installed: $(command -v claude)"
else
  echo "        installing via the official installer..."
  if [[ "$OSTYPE" == "darwin"* || "$OSTYPE" == "linux-gnu"* ]]; then
    curl -fsSL https://claude.ai/install.sh | bash
  else
    echo -e "        ${RED}unsupported OS for auto-install.${RESET} On Windows, run in PowerShell:"
    echo "        irm https://claude.ai/install.ps1 | iex"
    exit 1
  fi
fi

# 4. Write a launcher that sets the required env vars and starts Claude
#    Code against Ollama — no manual export lines to remember each time.
#    ANTHROPIC_API_KEY is intentionally empty and ANTHROPIC_AUTH_TOKEN is
#    a dummy value: Ollama's compatible endpoint doesn't check either,
#    they just need to be *set* so Claude Code doesn't prompt for auth.
echo -e "${YELLOW}[3/4]${RESET} writing run-claude-code.sh launcher..."
cat > run-claude-code.sh << EOF
#!/usr/bin/env bash
# Launches the real Claude Code CLI against Ollama (${OLLAMA_HOST}).
# Free, no Anthropic account. Generated by setup-claude-code.sh.
export ANTHROPIC_AUTH_TOKEN=ollama
export ANTHROPIC_API_KEY=""
export ANTHROPIC_BASE_URL="${OLLAMA_HOST}"
MODEL="\${1:-${DEFAULT_MODEL}}"
echo "Starting Claude Code with model: \${MODEL}"
claude --model "\${MODEL}" "\${@:2}"
EOF
chmod +x run-claude-code.sh

echo -e "${YELLOW}[4/4]${RESET} done."
echo
echo -e "${GREEN}${BOLD}Claude Code is configured to run against Ollama, free.${RESET}"
echo "  ./run-claude-code.sh                       # uses ${DEFAULT_MODEL}, this project's default"
echo "  ./run-claude-code.sh qwen2.5-coder:7b       # or any other pulled/pullable model"
echo
echo "  Note: local models need real tool-calling support to use Claude Code's"
echo "  file-edit/command tools properly — qwen3-coder, qwen2.5-coder, and"
echo "  glm-4.7-flash work noticeably better here than small general models."
echo "  A model needs to be pulled first: ollama pull <model>"
echo
echo "  Also worth knowing: Ollama's own docs recommend at least 32K tokens"
echo "  of context length for Claude Code to work well. A model running at"
echo "  a small default context window will truncate the conversation and"
echo "  can look like a model-quality problem when it's actually a"
echo "  context-window problem. Check with: ollama show <model>"
echo
